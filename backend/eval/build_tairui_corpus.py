def build() -> str:
    return "\n".join(_page(no, title, body)
                     for no, (title, body) in sorted(PAGES.items()))


def main() -> int:
    out = pathlib.Path(__file__).resolve().parent / "mock_corpus"
    out.mkdir(parents=True, exist_ok=True)
    path = out / "MOCK001_dd_package_2025.txt"
    text = build()
    path.write_text(text, encoding="utf-8")
    print(f"已生成 {path}")
    print(f"  {len(text)} 字符 / {len(PAGES)} 页")

    probes = ["客户", "供应商", "产能", "在建", "行业", "市场份额", "出口",
              "研发", "员工", "订单", "账期", "竞争"]
    hits = {kw: text.count(kw) for kw in probes}
    print("  清单覆盖不到的关键词命中：",
          "；".join(f"{k}×{v}" for k, v in hits.items() if v))
    missing = [k for k, v in hits.items() if not v]
    if missing:
        print(f"  ⚠️ 仍有 {missing} 未命中——调查层可能仍然产不出发现")
    for probe in ("持有惠州泰锐传动科技有限公司 30% 股权", "合计金额 4,000 万元"):
        assert probe.replace(" ", "") in text.replace(" ", ""), f"矛盾材料缺失：{probe}"
    print("  两处刻意矛盾均已写入（external_investment / guarantee）")
    return 0


